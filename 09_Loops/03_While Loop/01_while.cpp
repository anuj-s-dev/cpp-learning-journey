// While:- It is the alternate of for loop. In this we don't know how may times loop was running. It run untill condition was true.

// Question 1. Write a code to print a number from 1 to 100.

#include<iostream>
using namespace std;
int main()
{
    int i = 1;
    while (i<=100){
        cout<<i<<" ";
        i++;
    }
}