// Arrays:-(List of same datatypes)=> Arrays stores the values of same data type in contineous memory allocations.

#include <iostream>
using namespace std;
int main()
{
    int arr[5]; // Declaration

// Manual Way of taking input.

// Initialization value at every index :- Method 1.

    arr[0] = 9; // Set
    arr[1] = 8;
    arr[2] = 6;
    arr[3] = 4;
    arr[4] = 3;

    // Printing of Array :- Method 1.

    cout << arr[0] << " ";
    cout << arr[1] << " ";
    cout << arr[2] << " ";
    cout << arr[3] << " ";
    cout << arr[4] << " ";

}